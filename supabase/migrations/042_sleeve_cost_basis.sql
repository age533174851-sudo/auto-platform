-- 042_sleeve_cost_basis.sql
--
-- **전략 계좌의 손익이 영영 0이었다.**
--
-- 041로 만든 표는 소유 수량(positions)만 담는다. 그래서 체결이 나도
-- 수량만 옮겨 갔고 realized_pnl은 한 번도 안 움직였다. 그 결과:
--
--   · equityOf가 언제나 배정액과 같다 — 얼마를 잃어도
--   · 낙폭이 영원히 0% → 낙폭 정지가 **한 번도 못 걸린다**
--   · availableOf가 안 줄어 → 잃은 계좌가 계속 새로 들어간다
--
-- "한 전략이 손실 한도에 걸리면 그 전략만 멈춘다"가 전략 계좌를 나눈
-- 이유인데, 그 절반이 통째로 안 돌고 있었다.
--
-- 손익을 내려면 **얼마에 샀는지**를 알아야 한다. 거래소는 합계 포지션의
-- 평균가만 주므로(계좌가 하나니까) 전략별 평균가는 우리가 들고 있어야
-- 한다.
--
-- 왜 positions에 안 넣고 칸을 따로 두는가
-- ───────────────────────────────────────
-- positions는 소유권 판정(canClose)이 읽는 값이고, 이미 `{"BTCUSDT": 0.6}`
-- 모양으로 저장돼 있다. 여기에 객체를 섞으면 **이미 저장된 행을 전부
-- 옮겨야 하고**, 옮기다 실패한 행은 소유 수량을 잃는다. 칸을 더하는 쪽은
-- 기존 행을 건드리지 않는다.
--
-- 없는 것과 0은 다르다
-- ────────────────────
-- 이 칸에 심볼이 없으면 "이 계좌가 얼마에 샀는지 모른다"이고, 그때는
-- **청산 손익을 장부에 안 적는다.** 0으로 치면 전량이 이익으로 잡히고,
-- 그 숫자가 낙폭이 되고, 낙폭은 계좌를 멈추는 근거가 된다.
--
-- 041 이전에 열린 포지션이 정확히 그 상태다 — 평균가가 없다. 그 포지션의
-- 청산은 손익이 안 적히고, 응답에 그렇다고 적힌다.

ALTER TABLE strategy_accounts
  ADD COLUMN IF NOT EXISTS cost_basis JSONB NOT NULL DEFAULT '{}'::JSONB;

COMMENT ON COLUMN strategy_accounts.cost_basis IS
  '심볼 → 이 계좌의 매입 평균가. 없으면 모르는 것이고, 그때는 청산 손익을 적지 않는다';
