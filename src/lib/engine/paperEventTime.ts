// **모의 회계에서 "이 일이 언제 일어났는가"를 정하는 단 하나의 자리.**
//
// 왜 함수가 필요한가
// ──────────────────
// `085`의 회계 함수들은 `p_event_effective_at`을 반드시 받는다. 없으면 **돈을
// 건드리기 전에** 거부한다. 그래서 부르는 쪽은 시각을 만들어 넘겨야 하는데,
// 그 시각을 아무 데서나 만들면 두 가지가 바로 새어 들어온다.
//
//   · **클라이언트가 보낸 시각.** 요청 본문의 값이 그대로 원장에 박히면
//     사용자가 자기 챌린지의 사건 시각을 정할 수 있다. 유효기간 밖의 달성을
//     기간 안으로 적는 것이 가능해진다.
//   · **DB의 `DEFAULT now()`.** 칸에 기본값을 주면 "안 넘긴 것"과 "지금으로
//     정한 것"이 구별되지 않는다. 그래서 `083`은 이 칸에 기본값을 두지 않았다.
//
// 그래서 값을 **인자로 받지 않는다**
// ─────────────────────────────────
// 이 모듈은 시각을 **인자 없이** 만든다. 넘길 자리가 없으면 클라이언트 값이
// 들어올 길도 없다 — 검사기로 막는 것보다 통로 자체를 없애는 쪽이 낫다.
//
// 관측된 시장 시각이 생기면
// ─────────────────────────
// 지금 두 호출부(`openPaperPosition`·`closePaperPosition`)에는 시장 데이터의
// 시각이 들어오지 않는다. 체결가는 넘어오지만 그 가격이 **언제의 것인지**는
// 아무도 넘기지 않는다. 그것이 배선되는 단계에서 이 모듈에
// `fromObservedMarketTime(ms)`를 더하고, 그때도 값의 출처는 서버가 읽은
// 시장 데이터여야 한다. **요청 본문은 그때도 출처가 아니다.**

/**
 * 순수 서버 동작의 사건 시각.
 *
 * 서버가 **명시적으로** 지금을 사건 시각으로 정한다. DB 기본값이 아니라
 * 호출부가 정한 값이므로, 원장에 남은 시각이 어디서 왔는지 설명할 수 있다.
 */
export function paperEventTimeNow(): string {
  return new Date().toISOString();
}
